// 이름이 같거나 그 이름으로 시작하면(예: "더 알아두기 4개") 아이콘을 앞에 붙인다.
export function withIcon(label) {
  const key = Object.keys(ICON).find(k => label === k || label.startsWith(`${k} `));
  return key ? `${ICON[key]} ${label}` : label;
}
